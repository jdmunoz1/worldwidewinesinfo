export function getGrape(slug: string): Grape | undefined {
  return grapes.find((g) => g.slug === slug);
}

export function getGrapesByCountry(countrySlug: string): Grape[] {
  return grapes.filter((g) => g.majorCountries.map((c) => c.toLowerCase().replace(/[^a-z]/g, "")).includes(countrySlug));
}

export function getGrapesBySlugs(slugs: string[]): Grape[] {
  const map = new Map(grapes.map((g) => [g.slug, g]));
  return slugs.map((s) => map.get(s)).filter((g): g is Grape => Boolean(g));
}